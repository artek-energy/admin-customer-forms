const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const shared = path.join(root, "src", "gas", "quoteForms");
const output = path.join(root, "tmp", "quote-deployment");
const workflow = fs.readFileSync(path.join(shared, "QuoteWorkflow.gs"), "utf8");

for (const form of ["stationary", "mobile"]) {
  const destination = path.join(output, form);
  const definition = fs.readFileSync(path.join(root, "src", "gas", form + "Quote", "Code.gs"), "utf8");
  fs.mkdirSync(destination, { recursive: true });
  fs.writeFileSync(path.join(destination, "Code.gs"), "// Generated by npm run package:quotes. Edit the sources in src/gas.\n\n" + workflow + "\n" + definition);
  for (const file of ["QuoteSummary.html", "appsscript.json"]) {
    fs.copyFileSync(path.join(shared, file), path.join(destination, file));
  }
  const properties = path.join(destination, "script-properties.json");
  if (!fs.existsSync(properties)) {
    fs.writeFileSync(properties, JSON.stringify({
      QUOTE_SPREADSHEET_ID: "SET_EXISTING_SPREADSHEET_ID",
      QUOTE_FOLDER_ID: "SET_EXISTING_PDF_FOLDER_ID",
      QUOTE_SHEET_NAME: form === "stationary" ? "StationaryFormQuotes" : "MobileFormQuotes",
      QUOTE_OWNER_EMAILS: "sales@artek.energy"
    }, null, 2) + "\n");
  }
  console.log("Prepared " + form + " Apps Script project: " + destination);
}
